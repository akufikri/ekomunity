                <h2>1. Pengenalan</h2>
                <p>
                    eKomuniti ("kami", "kita", "platform") menghormati privasi anda dan komited untuk melindungi
                    maklumat peribadi yang anda kongsikan dengan kami. Polisi Privasi ini menerangkan cara kami
                    mengumpul, menggunakan, mendedahkan, dan melindungi maklumat peribadi anda apabila menggunakan
                    platform eKomuniti.
                </p>
                <p>
                    Dengan menggunakan platform eKomuniti, anda bersetuju dengan pengumpulan dan penggunaan maklumat
                    mengikut polisi ini.
                </p>

                <h2>2. Maklumat Yang Dikumpul</h2>
                <p>Kami mungkin mengumpul jenis maklumat berikut:</p>
                <ul>
                    <li><strong>Maklumat Akaun:</strong> Nama penuh, alamat e-mel, nombor telefon, alamat, dan maklumat organisasi/komuniti.</li>
                    <li><strong>Maklumat Log:</strong> Alamat IP, jenis pelayar, halaman yang dilawati, masa lawatan, dan data penggunaan lain.</li>
                    <li><strong>Maklumat Peranti:</strong> Jenis peranti, sistem operasi, pengecam peranti unik, dan tetapan rangkaian.</li>
                    <li><strong>Maklumat Pembayaran:</strong> Maklumat transaksi pembayaran yang diproses melalui pihak ketiga yang selamat (ToyyibPay).</li>
                    <li><strong>Kandungan Dihantar:</strong> Siaran, ulasan, gambar, dokumen, dan kandungan lain yang anda muat naik.</li>
                </ul>

                <h2>3. Cara Maklumat Digunakan</h2>
                <p>Maklumat anda digunakan untuk:</p>
                <ul>
                    <li>Menyediakan, menyelenggara, dan menambah baik platform eKomuniti.</li>
                    <li>Memproses pendaftaran dan pengurusan keahlian komuniti.</li>
                    <li>Menghantar notifikasi, kemas kini, dan komunikasi berkaitan perkhidmatan.</li>
                    <li>Memproses pembayaran dan yuran langganan.</li>
                    <li>Menganalisis penggunaan platform untuk meningkatkan pengalaman pengguna.</li>
                    <li>Mematuhi kewajipan undang-undang dan peraturan.</li>
                </ul>

                <h2>4. Perkongsian Maklumat</h2>
                <p>
                    Kami tidak menjual maklumat peribadi anda kepada pihak ketiga. Maklumat anda hanya dikongsi
                    dalam situasi berikut:
                </p>
                <ul>
                    <li><strong>Pembayaran:</strong> Dengan pemproses pembayaran pihak ketiga (ToyyibPay) untuk memproses transaksi.</li>
                    <li><strong>Pembekal Perkhidmatan:</strong> Dengan vendor yang membantu kami mengendalikan platform (hosting, analitik, push notification).</li>
                    <li><strong>Kewajipan Undang-undang:</strong> Apabila dikehendaki oleh undang-undang atau perintah mahkamah.</li>
                    <li><strong>Komuniti:</strong> Maklumat asas seperti nama dan jawatan dalam komuniti anda akan dipaparkan kepada ahli komuniti lain.</li>
                </ul>

                <h2>5. Keselamatan Data</h2>
                <p>
                    Kami mengambil langkah keselamatan yang munasabah dari segi teknikal dan organisasi untuk
                    melindungi maklumat peribadi anda daripada akses tanpa kebenaran, pengubahsuaian, pendedahan,
                    atau pemusnahan. Walau bagaimanapun, tiada kaedah penghantaran melalui internet atau
                    penyimpanan elektronik adalah 100% selamat.
                </p>

                <h2>6. Tempoh Penyimpanan Data</h2>
                <p>
                    Kami menyimpan maklumat peribadi anda selagi akaun anda aktif atau selama yang diperlukan untuk
                    menyediakan perkhidmatan kepada anda. Maklumat akan dipadamkan atau dinyahperibadikan selepas
                    tempoh yang munasabah selepas penamatan akaun, tertakluk kepada keperluan undang-undang.
                </p>

                <h2>7. Hak Anda</h2>
                <p>Anda mempunyai hak untuk:</p>
                <ul>
                    <li>Mengakses maklumat peribadi yang kami simpan.</li>
                    <li>Meminta pembetulan maklumat yang tidak tepat atau tidak lengkap.</li>
                    <li>Meminta pemadaman maklumat peribadi anda (tertakluk kepada keperluan undang-undang).</li>
                    <li>Menarik balik persetujuan pada bila-bila masa.</li>
                    <li>Meminta pengehadan pemprosesan data anda.</li>
                </ul>
                <p>Untuk melaksanakan hak-hak ini, sila hubungi kami melalui butiran di bawah.</p>

                <h2>8. Kuki</h2>
                <p>
                    Platform kami menggunakan kuki dan teknologi pengesanan lain untuk meningkatkan pengalaman
                    pengguna. Anda boleh mengawal penggunaan kuki melalui tetapan pelayar anda. Kuki digunakan
                    untuk:
                </p>
                <ul>
                    <li>Mengekalkan sesi log masuk anda.</li>
                    <li>Mengingati keutamaan dan tetapan anda.</li>
                    <li>Menganalisis corak penggunaan platform.</li>
                </ul>

                <h2>9. Pautan Pihak Ketiga</h2>
                <p>
                    Platform kami mungkin mengandungi pautan ke laman web pihak ketiga. Kami tidak bertanggungjawab
                    terhadap amalan privasi atau kandungan laman web tersebut. Kami menggalakkan anda untuk
                    membaca polisi privasi setiap laman web yang anda lawati.
                </p>

                <h2>10. Perubahan Kepada Polisi Privasi</h2>
                <p>
                    Kami mungkin mengemas kini Polisi Privasi ini dari semasa ke semasa. Sebarang perubahan akan
